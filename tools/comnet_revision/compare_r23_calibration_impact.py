#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Read-only effect analysis of R2.3 newly held-out calibration reference values.

Inputs generated by run_r23_heldout_calibration.py --mode analyze:
 - heldout_calibration_references.json
 - article_J_reference_comparison.csv

Outputs original-vs-new J summary in Markdown and CSV. The original cases and
original manuscript results are NOT modified.
"""
from __future__ import annotations
import argparse,csv,json,math,statistics
from collections import defaultdict
from pathlib import Path

METHODS=("FG-DSCR-GC","ILR-SA","LRScheduler","GAHRL","ORR","LASA")
SCALES=tuple(range(200,1001,100))

def writecsv(p,rows,cols):
    with p.open("w",newline="",encoding="utf-8") as f:
        w=csv.DictWriter(f,fieldnames=cols)
        w.writeheader();w.writerows(rows)

def main():
    p=argparse.ArgumentParser()
    p.add_argument("--dir",type=Path,default=Path("results/comnet_revision/reproducibility_r23/heldout_calibration"))
    args=p.parse_args()
    base=args.dir.resolve()
    path=base/"article_J_reference_comparison.csv"
    refs=json.loads((base/"heldout_calibration_references.json").read_text(encoding="utf-8"))
    with path.open(newline="",encoding="utf-8") as f:
        data=list(csv.DictReader(f))
    if len(data)!=54:raise RuntimeError(f"Expected exactly 54 main evaluation rows, got {len(data)}")
    values=defaultdict(dict)
    oldref=refs["old_article_reference_values"]
    newref=refs["reference_values"]
    for r in data:
        n=int(r["requests"]);method=r["method"]
        if n not in SCALES or method not in METHODS:raise RuntimeError("Unexpected request size/method "+str((n,method)))
        if method in values[n]:raise RuntimeError("Duplicated method-size record "+str((n,method)))
        d=float(r["D"]);ca=float(r["CA_rate"]);fr=float(r["Frag"])
        for val in (d,ca,fr):
            if not math.isfinite(val) or val<0:raise RuntimeError("Nonfinite or negative underlying metric")
        old=d/oldref["D"]+ca/oldref["CA"]+fr/oldref["Frag"]
        new=d/newref["D"]+ca/newref["CA"]+fr/newref["Frag"]
        if not math.isclose(old,float(r["J_article_original_reference"]),abs_tol=1e-9):
            raise RuntimeError("Historical J reference mismatch")
        if not math.isclose(new,float(r["J_new_heldout_reference"]),abs_tol=1e-9):
            raise RuntimeError("Heldout J reference mismatch")
        values[n][method]={"old":old,"new":new}
    if set(values)!=set(SCALES) or any(set(d)!=set(METHODS) for d in values.values()):
        raise RuntimeError("Missing methods or scales in original-54-data evaluation")

    ordered_methods=list(METHODS)
    avgs=[]
    for m in ordered_methods:
        a=statistics.mean(values[n][m]["old"] for n in SCALES)
        b=statistics.mean(values[n][m]["new"] for n in SCALES)
        avgs.append({"method":m,"old_avg_J":a,"new_avg_J":b,
                     "delta_J":b-a,"relative_J_change_pct":(b-a)/a*100 if a else 0})
    oldranking=sorted(avgs,key=lambda r:r["old_avg_J"])
    newranking=sorted(avgs,key=lambda r:r["new_avg_J"])
    for r in avgs:
        r["old_rank"]=1+next(i for i,z in enumerate(oldranking) if z["method"]==r["method"])
        r["new_rank"]=1+next(i for i,z in enumerate(newranking) if z["method"]==r["method"])
    writecsv(base/"article_J_method_summary.csv",avgs,
             ["method","old_avg_J","new_avg_J","delta_J","relative_J_change_pct","old_rank","new_rank"])

    head=["# R2.3 校准参考值改变对主实验 J 的影响","",
          "这是基于同一组原稿 54 条 D、CA、Frag 指标的只读重新归一化，不是重新运行主实验。","",
          "## 校准分母","",
          "| 指标 | 原稿历史参考值 | 新留出校准参考值 | 相对变化 |",
          "|---|---:|---:|---:|"]
    for label in ("D","CA","Frag"):
        a=oldref[label];b=newref[label]
        head.append(f"| {label}_ref | {a:.9f} | {b:.9f} | {(b-a)/a*100:+.2f}% |")
    head+=["","## 六种方法的九规模平均 J","",
           "| 方法 | 原稿 J | 新校准 J | 变化 | 原排名 | 新排名 |",
           "|---|---:|---:|---:|---:|---:|"]
    for r in sorted(avgs,key=lambda r:r["new_avg_J"]):
        head.append(f"| {r['method']} | {r['old_avg_J']:.6f} | {r['new_avg_J']:.6f} | "
                    f"{r['delta_J']:+.6f} | {r['old_rank']} | {r['new_rank']} |")

    head+=["","## 各规模的最优方法是否变化","",
           "| N | 原最优方法 | 新最优方法 | FALCONS 原 J | FALCONS 新 J |",
           "|---:|---|---|---:|---:|"]
    flip=[]
    for n in SCALES:
        before=min(METHODS,key=lambda m:values[n][m]["old"])
        after=min(METHODS,key=lambda m:values[n][m]["new"])
        if before!=after:flip.append((n,before,after))
        head.append(f"| {n} | {before} | {after} | "
                    f"{values[n]['FG-DSCR-GC']['old']:.6f} | "
                    f"{values[n]['FG-DSCR-GC']['new']:.6f} |")

    head+=["","## FALCONS 相对 Baselines 的平均改善幅度","",
           "按九个规模的平均 J 计算：改善百分比 = (baseline J - FALCONS J) / baseline J × 100%。","",
           "| Baseline | 历史归一化改善 | 新校准归一化改善 | 改变量（百分点） |",
           "|---|---:|---:|---:|"]
    fg=next(r for r in avgs if r["method"]=="FG-DSCR-GC")
    for r in avgs:
        if r["method"]=="FG-DSCR-GC":continue
        x=(r["old_avg_J"]-fg["old_avg_J"])/r["old_avg_J"]*100
        y=(r["new_avg_J"]-fg["new_avg_J"])/r["new_avg_J"]*100
        head.append(f"| {r['method']} | {x:+.2f}% | {y:+.2f}% | {y-x:+.2f} |")
    head+=["","## 结论边界","",
           "- 各方法使用的是完全相同的历史原始 D、CA、Frag，改变的只有三个 J 分母。",
           "- 新参考值由 3 个独立随机种子的留出抽样产生，仍源于同一份 DRTP profile，不是新采集的生产轨迹。",
           "- 原稿的历史参考值由主实验 54 条评价记录计算，不是独立校准。",
           "- 若新旧排名或相对改善幅度不同，论文所有涉及 J 的图表和文字须统一复核。",
           "- 本脚本没有重新评估二十种子结果、消融实验、缓存实验中的 J。采用新参考值须另行统一处理，不能只更新 Fig. 8。",
           "- 校准种子只有 3 个，参考值可能有采样波动，建议后续增加更多独立留出种子检验稳定性。",
           "",f"六种方法平均 J 排名是否改变：{'是' if [x['method'] for x in oldranking]!=[x['method'] for x in newranking] else '否'}。",
           f"九个请求规模最优方法变化数量：{len(flip)}。"]
    out=base/"article_J_impact_report.md"
    out.write_text("\n".join(head)+"\n",encoding="utf-8")
    print("Saved",out)
    print("Old J ranking:", " < ".join(r["method"] for r in oldranking))
    print("New J ranking:", " < ".join(r["method"] for r in newranking))
    print("Changed best method across scales:",len(flip))
    for r in sorted(avgs,key=lambda z:z["new_avg_J"]):
        print(f"{r['method']:<14} oldJ={r['old_avg_J']:.6f} newJ={r['new_avg_J']:.6f} "
              f"oldRank={r['old_rank']} newRank={r['new_rank']}")

if __name__=="__main__":
    main()
